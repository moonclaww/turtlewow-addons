local function AtlasGenerated_GetLegacyTable(category)
    if category == 1 then
        return AtlasText
    elseif category == 2 then
        return AtlasBG
    elseif category == 3 then
        return AtlasFP
    elseif category == 4 then
        return AtlasDL
    elseif category == 5 then
        return AtlasRE
    end
    return nil
end

if AceLibrary then
    local mapRegistry = AceLibrary("MapRegistry-1.0")
    if mapRegistry and mapRegistry.RegisterGeneratedManifest then
        mapRegistry:RegisterGeneratedManifest(AtlasGeneratedMaps.registry_manifest)
    end
end

for pageID, page in pairs(AtlasGeneratedMaps.pages) do
    local legacyTable = AtlasGenerated_GetLegacyTable(page.category)
    if legacyTable and page.source_key and legacyTable[page.source_key] then
        legacyTable[pageID] = legacyTable[page.source_key]
    end
end
